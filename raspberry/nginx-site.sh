#!/usr/bin/env bash
# DEVELOPED BY CARROTSTUDIO software house
# Prints the nginx configuration for Campanile. Used by install.sh.
#
#   raspberry/nginx-site.sh PORTAL HOSTNAME
#
# PORTAL is the hotspot address (e.g. 10.42.0.1), or "" without a hotspot.
# nginx faces the phones; the Python app and kiwix-serve listen on 127.0.0.1 only.
set -euo pipefail

PORTAL="${1-}"
HOSTNAME_LOCAL="${2:?missing hostname}"
CODE="${CAMPANILE_CODE:-/opt/campanile}"
DATA="${CAMPANILE_DATA:-/var/lib/campanile}"

[[ -z "$PORTAL" || "$PORTAL" =~ ^[0-9.]+$ ]] || { echo "invalid portal address" >&2; exit 1; }
[[ "$HOSTNAME_LOCAL" =~ ^[A-Za-z0-9.-]+$ ]] || { echo "invalid hostname" >&2; exit 1; }

# Only listen on IPv6 if the system has it, or nginx refuses to start.
IPV6=""
[ -e /proc/net/if_inet6 ] && IPV6=1

listen() {  # listen PORT [default]
  echo "    listen $1${2:+ default_server};"
  [ -n "$IPV6" ] && echo "    listen [::]:$1${2:+ default_server};"
  return 0
}

# No access log: we don't record who connects (and a flood can't fill the SD card).
quiet() {
  echo "    access_log off;"
  echo "    error_log /var/log/nginx/error.log crit;"
}

# add_header is not inherited by a location that sets its own, so every
# location serving our files repeats them.
headers() {
  cat <<'H'
        add_header X-Content-Type-Options "nosniff" always;
        add_header Referrer-Policy "no-referrer" always;
        add_header X-Frame-Options "DENY" always;
        add_header Content-Security-Policy "default-src 'self'; img-src 'self' data: blob:; worker-src 'self' blob:; connect-src 'self'; style-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'" always;
        add_header Cache-Control "no-cache" always;
H
}

# Every way into Campanile's API, written once. The phone's real address, overwriting anything
# the phone sent itself; one request per connection, so nothing a phone sends can be read there
# as a second request (written out: newer nginx no longer does it by default).
to_campanile() {
  cat <<'P'
        proxy_pass http://127.0.0.1:8080;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For "";
        proxy_http_version 1.0;
        proxy_set_header Connection close;
P
}

cat <<CONF
# DEVELOPED BY CARROTSTUDIO software house
# Generated by raspberry/nginx-site.sh: changes here are lost on reinstall.

limit_conn_zone \$binary_remote_addr zone=campanile_conn:1m;
limit_req_zone \$binary_remote_addr zone=campanile_api:1m rate=20r/s;
limit_req_zone \$binary_remote_addr zone=campanile_wiki:1m rate=10r/s;
CONF

if [ -n "$PORTAL" ]; then
  cat <<CONF

# Any other name (captive.apple.com, connectivitycheck...) goes to the portal:
# that's how phones open Campanile by themselves.
server {
$(listen 80 default)
    server_name _;
    server_tokens off;
$(quiet)
    return 302 http://$PORTAL/;
}
CONF
fi

DEFAULT=""
[ -z "$PORTAL" ] && DEFAULT=default

cat <<CONF

server {
$(listen 80 "$DEFAULT")
    server_name ${PORTAL:+$PORTAL }$HOSTNAME_LOCAL localhost 127.0.0.1;
    server_tokens off;
$(quiet)
    root $CODE/campanile/web;
    index index.html;

    # Slow or greedy clients: one phone can't take every connection or hold one forever.
    client_header_timeout 10s;
    client_body_timeout 10s;
    send_timeout 30s;
    keepalive_timeout 15s;
    client_max_body_size 8k;
    limit_conn campanile_conn 16;

    location / {
        try_files \$uri \$uri/ =404;
$(headers)
    }

    location ~ /\. {
        return 404;
    }

    # Debian's mime.types doesn't know .mjs: without this the browser refuses the map code.
    location ~ \.mjs\$ {
        types { }
        default_type "text/javascript; charset=utf-8";
$(headers)
    }

    location /vendor/fonts/ {
        types { }
        default_type application/x-protobuf;
$(headers)
    }

    # Only map files, straight from the data folder; nothing else in it is reachable.
    location ~ "^/maps/([A-Za-z0-9_-]+\.pmtiles)\$" {
        alias $DATA/maps/\$1;
        types { }
        default_type application/octet-stream;
        # Debian turns tcp_nopush on: each map tile then waited ~40 ms for the phone's
        # delayed ACK (measured, p95 48 ms -> 0.5 ms with it off).
        tcp_nopush off;
        # A tile at a time is never paced; a whole map is (server.py MAP_FREE, MAP_RATE).
        limit_rate_after 8m;
        limit_rate 128k;
$(headers)
    }

    location /maps/ {
        return 404;
    }

    # Maps and Wikipedia shared with another Campanile: big files, passed on as they are read
    # (buffered, nginx would write them to the SD card). Campanile checks the token and the pace.
    location /api/share/file/ {
        limit_req zone=campanile_api burst=40 nodelay;
$(to_campanile)
        proxy_buffering off;
        proxy_read_timeout 60s;
    }

    # A CAP alert passes 100 kB (server.py CAP_BODY). Only the admin page sends one, and it
    # works only on the Raspberry itself or through its SSH tunnel: the room, only for them.
    location = /api/admin/cap {
        allow 127.0.0.1;
        allow ::1;
        deny all;
        client_max_body_size 1025k;
        limit_req zone=campanile_api burst=40 nodelay;
$(to_campanile)
        proxy_read_timeout 30s;
    }

    location /api/ {
        limit_req zone=campanile_api burst=40 nodelay;
$(to_campanile)
        proxy_read_timeout 30s;
    }

}

# Wikipedia on its own port, so a different origin for the browser: whatever runs in a
# Kiwix page can't read Campanile's storage (the family plan) or act on its API.
server {
$(listen 8081)
    server_name _;
    server_tokens off;
$(quiet)
    client_header_timeout 10s;
    client_body_timeout 10s;
    send_timeout 30s;
    keepalive_timeout 15s;
    client_max_body_size 8k;
    limit_conn campanile_conn 16;

    location / {
        limit_req zone=campanile_wiki burst=40 nodelay;
        proxy_pass http://127.0.0.1:8082;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For "";
        proxy_http_version 1.0;
        proxy_set_header Connection close;
        proxy_read_timeout 60s;
        add_header X-Frame-Options "DENY" always;
        add_header Referrer-Policy "no-referrer" always;
    }
}
CONF
